class Solution:
    def compress(self, chars: List[str]) -> int:
        i = 0
        res = []

        while i < len(chars):
            ch = chars[i]
            count = 0

            while i < len(chars) and chars[i] == ch:
                count += 1
                i += 1

            res.append(ch)

            if count > 1:
                for digit in str(count):
                    res.append(digit)

        for i in range(len(res)):
            chars[i] = res[i]

        return len(res)