class Solution:
    def rotate(self, nums: List[int], k: int) -> None:
        n = len(nums)
        k = k % n

        temp = [0] * n
        j = 0

        for i in range(n - k, n):
            temp[j] = nums[i]
            j += 1

        for i in range(n - k):
            temp[j] = nums[i]
            j += 1

        for i in range(n):
            nums[i] = temp[i]

