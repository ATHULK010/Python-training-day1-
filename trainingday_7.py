from typing import List

class Solution:
    def exist(self, board: List[List[str]], word: str) -> bool:

        def possible(i, j, k):
            if k == len(word):
                return True

            if (i < 0 or i >= len(board) or
                j < 0 or j >= len(board[0]) or
                board[i][j] != word[k]):
                return False

            temp = board[i][j]
            board[i][j] = "#"

            found = (
                possible(i - 1, j, k + 1) or
                possible(i + 1, j, k + 1) or
                possible(i, j - 1, k + 1) or
                possible(i, j + 1, k + 1)
            )

            board[i][j] = temp  # backtrack
            return found

        for i in range(len(board)):
            for j in range(len(board[0])):
                if possible(i, j, 0):
                    return True

        return False

