class Solution:
    def nextGreaterElement(self, nums1: List[int], nums2: List[int]) -> List[int]:
        d={}
        st=[]
        for cur in nums2:
            while st and st[-1]<cur:
                ele=st.pop()
                d[ele]=cur
            st.append(cur)
        while st:
            d[st.pop()]=-1
        res=[]
        for i in nums1:
            res.append(d[i])
        return res

